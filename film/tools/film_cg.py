def refs_of(i):
    scene, who, _ = JOB[i]
    refs = [scene, "open_final"]
    for w in who:
        for a in (ANCHOR.get(w), EXTRA_ANCHOR.get(w)):
            if a and a not in refs: refs.append(a)
    return refs


def check(i):
    scene, who, _ = JOB[i]
    errs = [w for w in who if w not in ANCHOR]
    errs += [r for r in refs_of(i) if r not in art.REF or not os.path.exists(art.REF[r][0])]
    plan_who = PLAN[i]["who"]
    return errs


def register(i):
    scene, who, draw = JOB[i]
    art.JOBS["film_" + i] = dict(size="1536x1024", refs=refs_of(i), prompt=(
        f"影片《轉生成寶箱怪的我》補圖，橫幅 16:9。\n畫面：{draw}\n在場：{'、'.join(who)}（照各自的參考圖）。{CHAR}\n"
        f"場景、光線、色調照 Image 1。\n{art.S2D}畫風照 Image 1 與 Image 2。{art.NOTXT}"))


if __name__ == "__main__":
    assert set(JOB) == set(PLAN), f"計畫與工作不一致：{set(JOB) ^ set(PLAN)}"
    cmd, ids = sys.argv[1], sys.argv[2:] or list(JOB)
    bad = {i: check(i) for i in ids if check(i)}
    for i in ids: print(i, refs_of(i), "錯誤：" + str(bad[i]) if i in bad else "OK")
    if cmd == "run":
        if bad: sys.exit("有在場檢查沒過的，先修：" + str(bad))
        for i in ids: register(i)
        ts = [threading.Thread(target=art.run, args=("film_" + i,)) for i in ids]
        for t in ts: t.start()
        for t in ts: t.join()
